// Access properties using dot notation.

let student = {
  name: "jayant",
  age: 16,
  grade: 10,
  subjects: ["Math", "Science", "English"],
  isPassed: true,
};
console.log(student.name); // Output: jayant
console.log(student.age); // Output: 16
console.log(student.grade); // Output: 10
console.log(student.subjects); // Output: ["Math", "Science", "English"]
console.log(student.isPassed); // Output: true
